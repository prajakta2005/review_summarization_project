"""
Exports the report's master tables from results/*.json.

    python experiments/export_tables.py

Writes results/tables/<T>.csv and <T>.tex, and docs/RESULTS.md (Markdown
tables + key findings + provenance). Copy numbers into the report from
docs/RESULTS.md -- never retype them.
"""

import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from datetime import datetime, timezone

from results_io import list_results
from results_summary import (load_all_results, headline_numbers, key_findings, master_tables,
                             to_markdown_table, TABLE_TITLES)

TABLES_DIR = "results/tables"
RESULTS_MD = "docs/RESULTS.md"


def main():
    results = load_all_results()
    tables = master_tables(results)
    os.makedirs(TABLES_DIR, exist_ok=True)

    lines = [
        "# Experimental Results",
        "",
        "_Generated by `python experiments/export_tables.py` on "
        f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}. Do not edit by hand: "
        "re-run the experiments (`python experiments/run_all.py`) and this script instead._",
        "",
        "## Key findings",
        "",
        *[f"- {f}" for f in key_findings(headline_numbers(results))],
        "",
    ]
    for name, df in tables.items():
        df.to_csv(os.path.join(TABLES_DIR, f"{name}.csv"), index=False)
        with open(os.path.join(TABLES_DIR, f"{name}.tex"), "w", encoding="utf-8") as f:
            f.write(df.to_latex(index=False, float_format="%.4f", caption=TABLE_TITLES.get(name, name)))
        lines += [f"## {TABLE_TITLES.get(name, name)}", "", to_markdown_table(df), ""]
        print(f"exported {name} ({len(df)} rows)")

    lines += ["## Provenance", "", "| result | generated | commit | dataset | rows | script |",
              "|---|---|---|---|---|---|"]
    for m in list_results():
        lines.append(f"| {m['name']} | {m['generated_at']} | {m['git_commit']} | {m['dataset']} | "
                     f"{m['n_rows']:,} | `{m['script']}` |")
    with open(RESULTS_MD, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {RESULTS_MD} and {TABLES_DIR}/")


if __name__ == "__main__":
    main()
